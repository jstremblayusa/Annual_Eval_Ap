-- PBSci Annual Self-Evaluation Portfolio
-- Non-destructive setup: creates or updates configuration and faculty records.
-- It does NOT truncate tables or delete evaluations, activities, or reports.

create extension if not exists pgcrypto;

create table if not exists public.faculty (
  faculty_id uuid primary key default gen_random_uuid(),
  n_number text not null unique,
  first_name text not null,
  formal_first_name text not null default '',
  last_name text not null,
  position text not null,
  email text not null unique,
  system_role text not null default 'faculty' check (system_role in ('faculty','admin')),
  active boolean not null default true,
  display_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.access_links (
  access_link_id uuid primary key default gen_random_uuid(),
  faculty_id uuid not null references public.faculty(faculty_id) on delete cascade,
  token_hash text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  expires_at timestamptz,
  last_used_at timestamptz,
  revoked_at timestamptz
);

create table if not exists public.evaluations (
  evaluation_id uuid primary key default gen_random_uuid(),
  faculty_id uuid not null references public.faculty(faculty_id) on delete cascade,
  evaluation_year integer not null check (evaluation_year between 2020 and 2100),
  teaching_assignment text not null default '3/3',
  other_assignment text not null default '',
  teaching_fte_category text not null default '50% or greater',
  research_assignment_category text not null default '12.5–25%',
  service_assignment_category text not null default 'Typical service effort',
  sabbatical_status text not null default 'No',
  sabbatical_basis text not null default 'Typical research assignment',
  assignment_notes text not null default '',
  teaching_narrative text not null default '',
  research_narrative text not null default '',
  service_narrative text not null default '',
  status text not null default 'Draft',
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(faculty_id, evaluation_year)
);

create table if not exists public.scoring_rules (
  rule_id text primary key,
  portfolio_area text not null check (portfolio_area in ('teaching','research','service')),
  category text not null,
  activity_name text not null,
  minimum_points numeric not null,
  maximum_points numeric not null,
  unit_label text not null default 'activity',
  indicator_type text not null default '',
  instructions text not null default '',
  justification_required boolean not null default true,
  effective_year integer not null default 2026,
  display_order integer not null,
  active boolean not null default true,
  check (minimum_points >= 0 and maximum_points >= minimum_points)
);

create table if not exists public.rating_rules (
  rating_rule_id bigint generated by default as identity primary key,
  portfolio_area text not null,
  assignment_category text not null,
  rating text not null,
  rank_order integer not null,
  minimum_total numeric not null,
  maximum_total numeric,
  minimum_indicator_points numeric not null default 0,
  major_required boolean not null default false,
  unique(portfolio_area, assignment_category, rating)
);

create table if not exists public.minimum_requirements (
  requirement_id text primary key,
  portfolio_area text not null,
  requirement_text text not null,
  points numeric not null default 0,
  required boolean not null default true,
  display_order integer not null,
  active boolean not null default true
);

create table if not exists public.requirement_responses (
  response_id uuid primary key default gen_random_uuid(),
  evaluation_id uuid not null references public.evaluations(evaluation_id) on delete cascade,
  requirement_id text not null references public.minimum_requirements(requirement_id),
  met boolean not null default false,
  explanation text not null default '',
  updated_at timestamptz not null default now(),
  unique(evaluation_id, requirement_id)
);

create table if not exists public.activities (
  activity_id uuid primary key default gen_random_uuid(),
  evaluation_id uuid not null references public.evaluations(evaluation_id) on delete cascade,
  rule_id text not null references public.scoring_rules(rule_id),
  portfolio_area text not null,
  activity_title text not null,
  activity_period text not null default '',
  activity_description text not null,
  faculty_role text not null,
  time_effort text not null,
  supporting_information text not null,
  quantity integer not null default 1 check (quantity > 0),
  claimed_points_per_unit numeric not null,
  claimed_points_total numeric not null,
  point_justification text not null,
  possible_duplicate boolean not null default false,
  primary_portfolio_part text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

drop trigger if exists faculty_touch on public.faculty;
create trigger faculty_touch before update on public.faculty
for each row execute function public.touch_updated_at();
drop trigger if exists evaluations_touch on public.evaluations;
create trigger evaluations_touch before update on public.evaluations
for each row execute function public.touch_updated_at();
drop trigger if exists activities_touch on public.activities;
create trigger activities_touch before update on public.activities
for each row execute function public.touch_updated_at();
drop trigger if exists requirement_responses_touch on public.requirement_responses;
create trigger requirement_responses_touch before update on public.requirement_responses
for each row execute function public.touch_updated_at();

create or replace function public.request_token_hash()
returns text language sql stable security definer set search_path=public,extensions as $$
  select encode(digest(coalesce((current_setting('request.headers', true)::jsonb ->> 'x-access-token'), ''), 'sha256'), 'hex');
$$;

create or replace function public.current_faculty_id()
returns uuid language sql stable security definer set search_path=public as $$
  select al.faculty_id from public.access_links al
  where al.token_hash = public.request_token_hash()
    and al.active and al.revoked_at is null
    and (al.expires_at is null or al.expires_at > now())
  order by al.created_at desc limit 1;
$$;

create or replace function public.current_user_is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select coalesce((select f.system_role='admin' from public.faculty f
                   where f.faculty_id=public.current_faculty_id() and f.active), false);
$$;

create or replace function public.has_valid_access()
returns boolean language sql stable security definer set search_path=public as $$
  select public.current_faculty_id() is not null;
$$;

alter table public.faculty enable row level security;
alter table public.access_links enable row level security;
alter table public.evaluations enable row level security;
alter table public.scoring_rules enable row level security;
alter table public.rating_rules enable row level security;
alter table public.minimum_requirements enable row level security;
alter table public.requirement_responses enable row level security;
alter table public.activities enable row level security;

drop policy if exists faculty_read on public.faculty;
create policy faculty_read on public.faculty for select to anon
using (faculty_id=public.current_faculty_id() or public.current_user_is_admin());

drop policy if exists evaluation_all on public.evaluations;
create policy evaluation_all on public.evaluations for all to anon
using (faculty_id=public.current_faculty_id() or public.current_user_is_admin())
with check (faculty_id=public.current_faculty_id() or public.current_user_is_admin());

drop policy if exists rules_read on public.scoring_rules;
create policy rules_read on public.scoring_rules for select to anon using (public.has_valid_access());
drop policy if exists ratings_read on public.rating_rules;
create policy ratings_read on public.rating_rules for select to anon using (public.has_valid_access());
drop policy if exists requirements_read on public.minimum_requirements;
create policy requirements_read on public.minimum_requirements for select to anon using (public.has_valid_access());

drop policy if exists responses_all on public.requirement_responses;
create policy responses_all on public.requirement_responses for all to anon
using (exists(select 1 from public.evaluations e where e.evaluation_id=requirement_responses.evaluation_id
              and (e.faculty_id=public.current_faculty_id() or public.current_user_is_admin())))
with check (exists(select 1 from public.evaluations e where e.evaluation_id=requirement_responses.evaluation_id
                   and (e.faculty_id=public.current_faculty_id() or public.current_user_is_admin())));

drop policy if exists activities_all on public.activities;
create policy activities_all on public.activities for all to anon
using (exists(select 1 from public.evaluations e where e.evaluation_id=activities.evaluation_id
              and (e.faculty_id=public.current_faculty_id() or public.current_user_is_admin())))
with check (exists(select 1 from public.evaluations e where e.evaluation_id=activities.evaluation_id
                   and (e.faculty_id=public.current_faculty_id() or public.current_user_is_admin())));

grant usage on schema public to anon;
grant select on public.faculty, public.scoring_rules, public.rating_rules, public.minimum_requirements to anon;
grant select, insert, update on public.evaluations, public.requirement_responses, public.activities to anon;
grant delete on public.activities to anon;
grant execute on function public.request_token_hash() to anon;
grant execute on function public.current_faculty_id() to anon;
grant execute on function public.current_user_is_admin() to anon;
grant execute on function public.has_valid_access() to anon;

